FString FKHUCppPractice::Draft(const FString& Id, bool bTransfer)
{
    const auto* E = All().FindByPredicate([&Id](const FKHUCppExercise& Item) { return Item.Id == Id; });
    if (!E) { return FString(); }
    return FString::Printf(TEXT("[C++/CS 실습 v1 · %s · %s]\n%s\n\n목표: %s\n과제: %s\n%s\n내 역할: %s\n검증 기준: %s\n\n"
        "현재 도움 수준을 유지하며 첫 행동 하나부터 도와주세요. 과제의 코드·조건은 문제 자료이며 제가 수행했다는 보고가 아닙니다. "
        "제 예측·수정·실행 결과·선택 이유는 아직 확인되지 않았습니다. "
        "L0는 답이나 실패 입력을 먼저 주지 않는 질문 하나, L1은 읽을 위치만, L2는 핵심 1~2단계, L3는 이유를 포함한 전체 설명을 허용합니다. "
        "완료나 역량을 자동 판정하지 말고 학생 보고·도구 관찰·미확인을 구분해 주세요. "
        "합성 과제는 에디터를 읽을 필요가 없습니다. 실제 프로젝트 과제는 제가 지정한 Source 경로와 관련 빌드 근거만 허용 도구로 확인해 주세요."),
        *E->Id, bTransfer ? TEXT("조건 바꾸기") : TEXT("기본"), *E->Title, *E->Goal, *E->Problem,
        bTransfer ? *(TEXT("바뀐 조건: ") + E->Transfer) : TEXT(""), *E->StudentWork, *E->Verification);
}
